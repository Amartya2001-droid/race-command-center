import React from 'react';
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, test, vi } from 'vitest';
import App from '@/App';
const { invoke } = vi.hoisted(() => ({ invoke: vi.fn() }));
vi.mock('@/integrations/supabase/client', () => ({ supabase: { functions: { invoke } } }));
Object.defineProperty(window, 'matchMedia', { value: vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() })) });
afterEach(() => { cleanup(); vi.useRealTimers(); vi.clearAllMocks(); });
test('Settings changes the recording cadence, preserves pause and stops/resumes AI polling', async () => {
  vi.useFakeTimers();
  invoke.mockResolvedValue({ data: { predictions: [] }, error: null });
  render(<App />);
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }));
  fireEvent.change(screen.getByLabelText('Telemetry interval'), { target: { value: '1000' } });
  fireEvent.click(screen.getByLabelText('Enable AI risk polling'));
  fireEvent.click(screen.getByRole('button', { name: 'Done' }));
  fireEvent.click(screen.getByRole('button', { name: 'RECORD' }));
  act(() => { vi.advanceTimersByTime(999); });
  expect(screen.getByText('REC • 1 frames')).toBeTruthy();
  act(() => { vi.advanceTimersByTime(1); });
  expect(screen.getByText('REC • 2 frames')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'PAUSE' }));
  fireEvent.click(screen.getByRole('button', { name: 'Settings' }));
  fireEvent.change(screen.getByLabelText('Telemetry interval'), { target: { value: '500' } });
  act(() => { vi.advanceTimersByTime(30000); });
  expect(screen.getByText('REC • 2 frames')).toBeTruthy();
  expect(invoke).not.toHaveBeenCalled();
  fireEvent.click(screen.getByLabelText('Enable AI risk polling'));
  fireEvent.click(screen.getByRole('button', { name: 'Done' }));
  fireEvent.click(screen.getByRole('button', { name: 'RESUME' }));
  await act(async () => { vi.advanceTimersByTime(2000); });
  expect(invoke).toHaveBeenCalledTimes(1);
});
